#!/usr/bin/env python3
"""Rebuild seed.js from data/sets/*.json.

seed.js is only used when you open index.html directly (no server): it lets the
app start with your sets. Run this after adding or editing JSON set files:

    python3 tools/build_seed.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETS = os.path.join(ROOT, 'data', 'sets')


def main():
    sets = []
    for name in sorted(os.listdir(SETS)):
        if name.endswith('.json'):
            with open(os.path.join(SETS, name), encoding='utf-8') as fh:
                s = json.load(fh)
            s['id'] = name[:-5]
            # seeds start with clean stats
            for c in s.get('cards', []):
                c.update(right=0, wrong=0, lastWrong=False, learn=0)
            sets.append(s)
    sets.sort(key=lambda s: -s.get('updatedAt', 0))
    with open(os.path.join(ROOT, 'seed.js'), 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/build_seed.py from data/sets/*.json — do not edit by hand.\n'
                 '   Used only when index.html is opened without server.py. */\n')
        fh.write('window.SEED_SETS = ' + json.dumps(sets, ensure_ascii=False, indent=1) + ';\n')
    print(f'seed.js: {len(sets)} sets, {sum(len(s["cards"]) for s in sets)} cards')


if __name__ == '__main__':
    main()
